import { mkdir, readdir, readFile, writeFile, cp, stat } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import sharp from 'sharp';

const root = fileURLToPath(new URL('../', import.meta.url));
const dist = path.join(root, 'dist');
const icon = await readFile(path.join(root, 'iconos/tgi.svg'));
for (const [name, size] of [['tgi-192.png', 192], ['tgi-512.png', 512], ['apple-touch-icon.png', 180]]) {
  await sharp(icon).resize(size, size).png().toFile(path.join(root, 'iconos', name));
}
// Keep the entire mark in the central maskable safe area.
const inset = await sharp(icon).resize(384, 384).png().toBuffer();
await sharp({ create: { width: 512, height: 512, channels: 4, background: '#362060' } })
  .composite([{ input: inset, left: 64, top: 64 }]).png().toFile(path.join(root, 'iconos/tgi-maskable-512.png'));

const filesIn = async dir => (await readdir(path.join(root, dir))).sort().map(file => dir + '/' + file);
const shell = ['index.html', 'estilos.css', 'movil.css', 'app.js', 'busqueda.js', 'pwa.js', 'manifest.webmanifest',
  ...await filesIn('datos'), ...await filesIn('iconos')];
const assets = [...await filesIn('imagenes'), ...await filesIn('textos')];
async function fingerprint(files) {
  const hash = createHash('sha256');
  for (const file of files) { hash.update(file); hash.update(await readFile(path.join(root, file))); }
  return hash.digest('hex').slice(0, 16);
}
const bytes = (await Promise.all(assets.map(file => stat(path.join(root, file))))).reduce((sum, file) => sum + file.size, 0);
const mediaVersion = await fingerprint(assets);
const config = {
  coreVersion: createHash('sha256').update(await fingerprint([...shell, 'sw.js'])).update(mediaVersion).digest('hex').slice(0, 16),
  mediaVersion,
  bytes,
  shell: [...shell, 'offline-manifest.js'],
  assets
};
await writeFile(path.join(root, 'offline-manifest.js'), '// Generated by npm run build; keep this file for file:// use.\n' + 'globalThis.TGI_OFFLINE = ' + JSON.stringify(config, null, 2) + ';\n');
await mkdir(dist, { recursive: true });
for (const file of [...config.shell, 'sw.js', 'cobertura.json', 'LEEME.txt', ...assets]) {
  await mkdir(path.dirname(path.join(dist, file)), { recursive: true });
  await cp(path.join(root, file), path.join(dist, file));
}
console.log(`TGI lista en dist/: ${assets.length} archivos de consulta, ${Math.round(bytes / 1e6)} MB. Versión ${config.coreVersion}.`);
